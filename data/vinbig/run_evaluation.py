import json
import requests
import os
from dotenv import load_dotenv

# Load OpenAI API Key from environment variables
load_dotenv()
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

# --- Configuration ---
API_URL = "http://127.0.0.1:8000/api/v1/analyze"
JSON_PATH = "dataset.json"

# --- AI Judge Function (Extract Confirmed List Version) ---
def llm_judge(ai_report):
    """Ask GPT to read the report and extract the definitively diagnosed disease list."""
    judge_prompt = f"""
    You are a strict, highly accurate medical AI evaluation judge.
    Please carefully read the following medical report generated by an AI agent:
    
    "{ai_report}"
    
    Task: Extract a list of diseases that the AI report has "definitively diagnosed" or "confirmed" strictly based ON IMAGING FINDINGS.
    
    [ CRITICAL RULES ]:
    1. If a disease is only mentioned based on the user's description (e.g. "Based on your description...") and DOES NOT have supporting imaging findings, DO NOT include it in the list.
    2. Only include diseases explicitly supported by CV findings or imaging evidence within the report.
    3. If no definitive diagnoses are established by imaging, return an empty list [].
    
    You must output in JSON format:
    {{
        "reasoning": "A one-sentence explanation of your judgment...",
        "diagnosed_diseases": ["DiseaseA", "DiseaseB"] 
    }}
    """

    headers = {
        "Authorization": f"Bearer {OPENAI_API_KEY}",
        "Content-Type": "application/json"
    }
    
    payload = {
        "model": "gpt-4o-mini",
        "temperature": 0.0,  # [ STRICT ] Maintain absolute rationality
        "messages": [{"role": "user", "content": judge_prompt}],
        "response_format": {"type": "json_object"}
    }

    try:
        resp = requests.post("https://api.openai.com/v1/chat/completions", headers=headers, json=payload)
        if resp.status_code == 200:
            result_text = resp.json()["choices"][0]["message"]["content"]
            result_dict = json.loads(result_text)
            print(f"   [ REASONING ] Judge's reasoning: {result_dict.get('reasoning', 'None')}")
            return result_dict.get("diagnosed_diseases", [])
        else:
            print(f"[ WARNING ] Judge AI connection error: {resp.text}")
            return []
    except Exception as e:
        print(f"[ ERROR ] Judge AI exception error: {e}")
        return []

# --- Main Program ---
def run_eval():
    print("[ START ] Starting MedAgentCV Automated Evaluation Test (Including F1-Score)...\n")
    
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        dataset = json.load(f)
    
    test_cases = dataset  # Execute all test cases
    
    # Initialize global scoreboard (TP, FP, FN)
    global_tp = 0
    global_fp = 0
    global_fn = 0
    
    for i, case in enumerate(test_cases, 1):
        img_path = case['image_path']
        clinical_note = case['clinical_note']
        true_labels = case['image_labels']  # Ground truth
        
        print(f"\n--- Test Case {i}/{len(test_cases)} ---")
        print(f"[ PATH ] Image Path: {img_path}")
        print(f"[ TARGET ] Ground Truth: {true_labels}")
        
        if not os.path.exists(img_path):
            print(f"[ ERROR ] Image not found {img_path}\n")
            continue
            
        try:
            with open(img_path, 'rb') as img_file:
                files = {'image': img_file}
                data = {'disease_description': clinical_note}
                
                print("[ PENDING ] Waiting for MedAgentCV analysis...")
                response = requests.post(API_URL, files=files, data=data)
                
                if response.status_code == 200:
                    result = response.json()
                    ai_analysis = result.get('final_analysis', '')
                    
                    print("[ SYSTEM ] Calling AI Judge for scoring...")
                    # Get the list of diseases the AI Judge determined as diagnosed by the Agent
                    predicted_labels = llm_judge(ai_analysis)
                    print(f"[ RESULT ] AI Diagnosed Result: {predicted_labels}")
                    
                    # Convert lists to Sets for union and difference operations
                    true_set = set(true_labels)
                    pred_set = set(predicted_labels)
                    
                    # Calculate TP, FP, FN for this case
                    tp = len(true_set & pred_set)  # Both have it (True Positive)
                    fp = len(pred_set - true_set)  # AI predicted but not in ground truth (False Positive)
                    fn = len(true_set - pred_set)  # Ground truth has it but AI missed (False Negative)
                    
                    # Accumulate to global scoreboard
                    global_tp += tp
                    global_fp += fp
                    global_fn += fn
                    
                else:
                    print(f"[ WARNING ] API Error: Status code {response.status_code}")
                    
        except Exception as e:
            print(f"[ CRITICAL ] Unexpected error occurred: {e}\n")

    # --- Execution completed, calculate final golden metrics ---
    print("\n" + "="*50)
    print("[ REPORT ] MedAgentCV Final Evaluation Report")
    print("="*50)
    print(f"Total True Positives (TP)  : {global_tp}")
    print(f"Total False Positives (FP) : {global_fp}")
    print(f"Total False Negatives (FN) : {global_fn}")
    print("-"  *50)
    
    # Protection against division by zero
    precision = global_tp / (global_tp + global_fp) if (global_tp + global_fp) > 0 else 0
    recall = global_tp / (global_tp + global_fn) if (global_tp + global_fn) > 0 else 0
    f1_score = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
    
    print(f"[ METRIC ] Precision : {precision * 100:.2f}%")
    print(f"[ METRIC ] Recall    : {recall * 100:.2f}%")
    print(f"[ METRIC ] F1-Score  : {f1_score * 100:.2f}%")
    print("="*50)

if __name__ == "__main__":
    run_eval()